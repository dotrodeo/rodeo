// @ts-check
import { defineConfig } from 'astro/config';
import sitemap from '@astrojs/sitemap';
import mdx from '@astrojs/mdx';
import starlight from '@astrojs/starlight';
import tailwindcssPlugin from '@tailwindcss/vite';
import { existsSync, readdirSync, readFileSync } from 'node:fs';

// Astro and @tailwindcss/vite currently resolve different copies of Vite's
// types, so the plugin's `this` context does not structurally match. The
// plugin is correct at runtime; only the declarations skew, so the array is
// widened rather than the behaviour changed.
/** @type {any[]} */
const vitePlugins = [tailwindcssPlugin()];

// An autogenerated sidebar group whose pages are all `draft: true` still renders
// its heading in a production build, with nothing under it. The SDK's Guides are
// design drafts until their code lands, so the group appears only once one is
// published, or under `astro dev`, which shows drafts.
const SDK_GUIDES = new URL('../rodeo-sdk/docs/guides/', import.meta.url);
const sdkGuidesPublished = existsSync(SDK_GUIDES) && readdirSync(SDK_GUIDES)
  .filter((f) => f.endsWith('.mdx') || f.endsWith('.md'))
  .some((f) => !/^draft:\s*true\s*$/m.test(readFileSync(new URL(f, SDK_GUIDES), 'utf8')));
const astroDev = process.argv.includes('dev');

// `site` is load-bearing: canonical URLs, OG cards, the sitemap and (later)
// the RSS feed Buttondown consumes all derive from it.
export default defineConfig({
  site: 'https://rodeooh.rodeo',
  output: 'static',
  trailingSlash: 'always',
  build: { format: 'directory' },
  integrations: [
    // Starlight owns /sdk/ only. The marketing pages, the board catalogue and
    // the build log keep their own layout; this is a docs section inside the
    // site rather than a second site bolted on.
    starlight({
      title: 'Rodeo',
      // Starlight builds its own <head>, so BaseHead's Open Graph tags never
      // reach /docs/ or /sdk/. Without these the documentation shares as a
      // blank large-image card. One card covers both sections.
      head: [
        {
          tag: 'meta',
          attrs: { property: 'og:image', content: 'https://rodeooh.rodeo/og/docs.png' },
        },
        { tag: 'meta', attrs: { property: 'og:image:width', content: '1200' } },
        { tag: 'meta', attrs: { property: 'og:image:height', content: '630' } },
        { tag: 'meta', attrs: { name: 'twitter:card', content: 'summary_large_image' } },
        {
          tag: 'meta',
          attrs: { name: 'twitter:image', content: 'https://rodeooh.rodeo/og/docs.png' },
        },
      ],
      // Covers /docs/ and /sdk/ both, so it cannot be only about the SDK.
      description:
        'Hardware and firmware documentation for Rodeo — pinouts, the satellite chain contract, driver libraries and bring-up examples.',
      customCss: ['./src/styles/starlight.css'],
      expressiveCode: {
        // Starlight's default syntax theme is a Material-ish purple/orange set
        // that has nothing to do with this palette, and its code surface sits
        // 1.11:1 from the page so blocks never detach. Everything below is
        // legibility and separation, not decoration.
        themes: ['github-dark-default'],
        styleOverrides: {
          borderRadius: '0',
          borderColor: '#3a3a3a',
          codeBackground: '#191919',
          frames: {
            editorActiveTabBackground: '#191919',
            editorTabBarBackground: '#141414',
            terminalBackground: '#191919',
            terminalTitlebarBackground: '#141414',
          },
        },
      },
      // The site has its own 404; Starlight must not claim that route.
      disable404Route: true,
      // Dark only; the toggle is overridden with an empty component.
      components: {
        ThemeSelect: './src/components/starlight/ThemeSelect.astro',
        Header: './src/components/starlight/Header.astro',
        MobileMenuFooter: './src/components/starlight/MobileMenuFooter.astro',
      },
      social: [
        { icon: 'github', label: 'GitHub', href: 'https://github.com/dotrodeo/rodeo' },
      ],
      sidebar: [
        {
          label: 'Hardware',
          items: [
            { label: 'Overview', slug: 'docs' },
            { label: 'Pinout', slug: 'docs/pinout' },
            { label: 'Satellite chain', slug: 'docs/satellite-chain' },
            { label: 'Mechanical', slug: 'docs/mechanical' },
          ],
        },
        {
          label: 'Start here',
          items: [
            { label: 'Overview', slug: 'sdk' },
            { label: 'Install and build', slug: 'sdk/install' },
            { label: 'Your first app', slug: 'sdk/first-app' },
          ],
        },
        // Design drafts for APIs not written yet carry `draft: true`: shown by
        // `astro dev`, left out of the built site until their code lands.
        ...(sdkGuidesPublished || astroDev
          ? [{ label: 'Guides', autogenerate: { directory: 'sdk/guides' } }]
          : []),
        {
          label: 'Reference',
          items: [
            { label: 'Pure-logic headers', slug: 'sdk/reference/pure-logic' },
            { label: 'Examples', slug: 'sdk/reference/examples' },
            { label: 'Versioning', slug: 'sdk/reference/versioning' },
          ],
        },
        // Generated from the headers by rodeo-sdk/tools/docs/gen_reference.py.
        { label: 'API reference', autogenerate: { directory: 'sdk/reference/api' } },
      ],
    }),
    mdx(),
    // The signup confirmation is noindex; listing it in the sitemap would ask
    // search engines to crawl exactly the page the meta tag tells them to drop.
    sitemap({ filter: (page) => !page.endsWith('/subscribe/thanks/') }),
  ],
  vite: { plugins: vitePlugins },
});
